		version = "*",
		config = function()
			require("toggleterm").setup({
				size = 15, -- Default size of terminal
				open_mapping = [[<C-c>]], -- Default key mapping for float term
				direction = "float", -- Default terminal direction
				insert_mappings = true,
				float_opts = {
					border = "curved", -- Border style for floating terminal
					-- winblend = 35, -- Transparency level
					height = 30, -- prev: 40
					width = 80, -- prev: 100
					title_pos = "left",
				},
			})
		end,
	},
